// Bundle local ES modules as import-map data URLs so file:// needs no HTTP server.
// The normal web entry keeps using the original independently cached modules.
import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const modules=new Map();
const imports=/^\s*(?:import|export)\s+(?:[\w*\s{},]+?\s+from\s+)?(['"])(\.[^'"]+)\1\s*;/gm;
async function collect(file){
    if(modules.has(file))return;
    let source=(await fs.readFile(path.join(root,file),'utf8')).replaceAll('\r\n','\n');
    modules.set(file,'');
    if(file==='art/asset-revisions.js')source="export const ASSET_REVISION='local';export const ASSET_HASHES={};";
    const dependencies=[...source.matchAll(imports)].map(match=>match[2]);
    for(const dependency of dependencies)await collect(path.posix.normalize(path.posix.join(path.posix.dirname(file),dependency)));
    source=source.replace(imports,(statement,quote,specifier)=>{
        const resolved=path.posix.normalize(path.posix.join(path.posix.dirname(file),specifier));
        return statement.replace(quote+specifier+quote,quote+'populate/'+resolved+quote);
    }).replaceAll('import.meta.url','new URL('+JSON.stringify(file)+',document.baseURI).href');
    modules.set(file,'data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
}
const html=await fs.readFile(path.join(root,'PopulateTheRebeginning.html'),'utf8');
const entry=html.match(/<script type="module">([\s\S]*?)<\/script>/)[1];
for(const match of entry.matchAll(imports))await collect(path.posix.normalize(match[2]));
const pairs=[...modules].sort(([a],[b])=>a.localeCompare(b));
const inventory=JSON.parse(await fs.readFile(path.join(root,'licenses/vendor.json'),'utf8'));
const notices=[...new Set(inventory.components.filter(component=>Object.keys(component.files).some(file=>modules.has(file)))
    .flatMap(component=>component.notices))];
const licenseText=(await Promise.all(notices.map(file=>fs.readFile(path.join(root,file),'utf8')))).join('\n').replaceAll('\r\n','\n');
const bundle='/* Bundled third-party license notices\n'+licenseText.replaceAll('*/','* /')+'\n*/\n'+
    '// Generated by tools/build-offline-runtime.mjs. Contains project code and bundled vendor code.\n'+
    '// Third-party license notices remain in vendor/*-LICENSE.txt and licenses/vendor.json.\n'+
    '(function(){const modules='+JSON.stringify(pairs)+';const imports={};'+
    'for(const [file,url] of modules){imports["populate/"+file]=url;imports[new URL(file,document.baseURI).href]=url;}'+
    'const map=document.createElement("script");map.type="importmap";map.textContent=JSON.stringify({imports});document.head.appendChild(map);})();\n';
await fs.writeFile(path.join(root,'offline-runtime.js'),bundle);
console.log(JSON.stringify({localModules:pairs.length,bytes:Buffer.byteLength(bundle)}));
