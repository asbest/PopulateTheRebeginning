import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';

const root=path.resolve(import.meta.dirname,'..');
const sharpPath=process.argv.find(arg=>arg.startsWith('--sharp='))?.slice(8);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex').slice(0,16);
const out=path.join(root,'art/startup');
await fs.mkdir(path.join(out,'textures'),{recursive:true});
await fs.mkdir(path.join(out,'models'),{recursive:true});
const previews={},modelGroups={},modelFiles={},generated=new Set();
if(!process.argv.includes('--manifest-only')){
 const sharp=createRequire(import.meta.url)(sharpPath||'sharp');
 await sharp(await fs.readFile(path.join(root,'art/key-art.png')))
  .resize({width:1280,height:1280,fit:'inside',withoutEnlargement:true}).webp({quality:82,effort:5})
  .toFile(path.join(root,'art/key-art-startup.webp'));
 const sources=['art/character-cloth.png','art/character-skin-v2.png'];
 for(const folder of ['art/blender','art/materials'])for(const file of await fs.readdir(path.join(root,folder)))
  if(/\.(png|webp)$/i.test(file))sources.push(`${folder}/${file}`);
 let sourceBytes=0,previewBytes=0;
 for(const source of sources.sort()){
  const bytes=await fs.readFile(path.join(root,source));
  const preview=await sharp(bytes).resize({width:256,height:256,fit:'inside',withoutEnlargement:true})
   .webp(/-(normal|roughness)\.png$/.test(source)?{lossless:true}:{quality:82,effort:5}).toBuffer();
  const name=`textures/${source.replace(/^art\//,'').replaceAll('/','-').replace(/\.(png|webp)$/i,'')}.${hash(preview)}.webp`;
  await fs.writeFile(path.join(out,name),preview);generated.add(name);previews[source]=`art/startup/${name}`;
  sourceBytes+=bytes.length;previewBytes+=preview.length;
 }
 const pack=JSON.parse(await fs.readFile(path.join(root,'art/blender/mesh-pack.json'),'utf8'));
 const groups={startup:{},warrior:{},firewarrior:{},spy:{},airship:{},tower:{}};
 for(const [key,data] of Object.entries(pack.models)){
  const group=key.startsWith('character/warrior/')||key.startsWith('building/warrior/')?'warrior'
   :key.startsWith('character/firewarrior/')||key.startsWith('building/fire/')?'firewarrior'
   :key.startsWith('character/spy/')||key.startsWith('building/spy/')?'spy'
   :key.startsWith('character/airship/')||key.startsWith('building/shipyard/')?'airship'
   :key.startsWith('building/tower/')?'tower':'startup';
  groups[group][key]=data;modelGroups[key]=group;
 }
 for(const [group,models] of Object.entries(groups)){
  const bytes=Buffer.from(JSON.stringify({version:pack.version,models}));
  const name=`models/${group}.${hash(bytes)}.json`;
  await fs.writeFile(path.join(out,name),bytes);generated.add(name);modelFiles[group]=`art/startup/${name}`;
 }
 for(const folder of ['textures','models'])for(const name of await fs.readdir(path.join(out,folder)))
  if(!generated.has(`${folder}/${name}`))await fs.unlink(path.join(out,folder,name));
 await fs.writeFile(path.join(root,'art/startup-manifest.js'),
  '// Generated by tools/build-startup-assets.mjs.\n'+
  `export const TEXTURE_PREVIEWS=${JSON.stringify(previews)};\n`+
  `export const MODEL_GROUPS=${JSON.stringify(modelGroups)};\n`+
  `export const MODEL_FILES=${JSON.stringify(modelFiles)};\n`);
 console.log(JSON.stringify({textures:sources.length,sourceBytes,previewBytes,models:Object.fromEntries(Object.entries(groups).map(([group,models])=>[group,Object.keys(models).length]))}));
}
const files={};
async function scan(folder){
 for(const entry of await fs.readdir(path.join(root,folder),{withFileTypes:true})){
  if(entry.name==='node_modules'||entry.name.startsWith('.'))continue;
  const relative=folder?`${folder}/${entry.name}`:entry.name;
  if(entry.isDirectory()){if(['art','vendor','sfx'].includes(relative)||folder)await scan(relative);continue;}
  if(!/\.(js|wasm|json|png|webp|ktx2|wav|mp3|mp4|html|css)$/i.test(relative))continue;
  if(['art/asset-revisions.js','asset-cache-manifest.js'].includes(relative))continue;
  if(!folder&&!/\.(mp3|mp4|html|js)$/.test(relative))continue;
  const bytes=await fs.readFile(path.join(root,relative));
  // Git may check text out as CRLF on Windows and LF on the deployment runner.
  files[relative]=hash(/\.(js|json|html|css)$/i.test(relative)?bytes.toString('utf8').replaceAll('\r\n','\n'):bytes);
 }
}
await scan('');
const revision=hash(JSON.stringify(files));
await fs.writeFile(path.join(root,'art/asset-revisions.js'),`// Generated by tools/build-startup-assets.mjs.\nexport const ASSET_REVISION=${JSON.stringify(revision)};\nexport const ASSET_HASHES=${JSON.stringify(files)};\n`);
await fs.writeFile(path.join(root,'asset-cache-manifest.js'),`// Generated by tools/build-startup-assets.mjs.\nself.GAME_ASSETS=${JSON.stringify({revision,files})};\n`);
console.log(JSON.stringify({revision,versionedFiles:Object.keys(files).length}));
