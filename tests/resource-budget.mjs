import assert from 'node:assert/strict';
import {createResourceBudget} from '../art/resource-budget.js';
let clock=0;const callbacks=[],executed=[];
const budget=createResourceBudget({now:()=>clock,schedule:cb=>callbacks.push(cb)});
const step=()=>{assert(callbacks.length);callbacks.shift()();};
budget.frame(5,false);
const once=budget.enqueue('same',()=>executed.push('once'));
assert.equal(once,budget.enqueue('same',()=>executed.push('duplicate')));
budget.enqueue('urgent',()=>executed.push('urgent'),-2);
step();assert.deepEqual(executed,['urgent']);step();await once;assert.deepEqual(executed,['urgent','once']);
budget.frame(40,false);budget.enqueue('busy',()=>executed.push('busy'));step();assert.equal(executed.length,2);
budget.frame(5,false);step();assert.equal(executed.at(-1),'busy');
budget.frame(5,false,false,true);
budget.enqueue('shader',()=>executed.push('shader'),1);budget.enqueue('texture',()=>executed.push('texture'),-2);
step();assert.equal(executed.at(-1),'texture');step();assert.equal(executed.at(-1),'texture');
budget.frame(5,true);step();assert.equal(executed.at(-1),'shader');
const removed=budget.enqueue('unloaded',()=>{throw Error('Disposed geometry was processed');});budget.cancel('unloaded');step();assert.equal(await removed,false);
budget.frame(5,false);budget.enqueue('slow',()=>{clock+=8;});step();budget.enqueue('next',()=>executed.push('next'));step();
assert.notEqual(executed.at(-1),'next');for(let i=0;i<3;i++)step();assert.equal(executed.at(-1),'next');
const failure=budget.enqueue('failure',()=>{throw Error('GPU unavailable');}).catch(e=>e.message);step();assert.equal(await failure,'GPU unavailable');
budget.enqueue('after-failure',()=>executed.push('recovered'));step();assert.equal(executed.at(-1),'recovered');assert.equal(budget.stats.errors,1);
assert.equal(budget.stats.maxStepMs,8);assert.equal(budget.stats.queued,0);
console.log('PASS resource preparation deduplicates, prioritizes uploads, yields busy/combat frames, backs off and cancels unloaded geometry');
